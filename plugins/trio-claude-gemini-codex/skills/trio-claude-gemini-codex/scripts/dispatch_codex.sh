#!/usr/bin/env bash
# Usage: dispatch_codex.sh <ticket-file> <task-dir>
# Runs Codex CLI on a ticket in its own git worktree/branch (mm/<task>-codex), based on the
# current HEAD (uncommitted changes are NOT included). Commits only after a successful run.
set -uo pipefail
source "$(dirname "$0")/_lib.sh"
[ $# -eq 2 ] || die "usage: dispatch_codex.sh <ticket-file> <task-dir>"
ticket="$1"; taskdir="$(cd "$2" && pwd)" || die "task dir not found: $2"
[ -f "$ticket" ] || die "ticket not found: $ticket"
command -v codex >/dev/null || die "codex CLI not installed (npm i -g @openai/codex, then: codex login)"
root="$(git rev-parse --show-toplevel 2>/dev/null)" || die "not inside a git repository"
slug="$(basename "$taskdir")"; branch="mm/${slug}-codex"; # Keep the worktree OUTSIDE the repo so reviewers and scouts do not see duplicate files.
lock="$taskdir/.codex-dispatch.lock"
mkdir "$lock" 2>/dev/null || die "dispatch lock exists: $lock (check for an active dispatch)"
trap 'rmdir "$lock"' EXIT
receipt="$taskdir/05-receipt-codex.md"; log="$taskdir/05-codex-log.txt"
pending_receipt="$taskdir/05-receipt-codex.partial.md"
[ ! -e "$receipt" ] || die "receipt already exists for this run: $receipt (start a new task for another dispatch)"
wt="${MM_WORKTREES:-$HOME/.multimodel-worktrees}/$(basename "$root")/${slug}-codex"
mkdir -p "$(dirname "$wt")" || die "could not create worktree parent"
wt="$(cd "$(dirname "$wt")" && pwd -P)/$(basename "$wt")"
if [ ! -d "$wt" ]; then
  if git -C "$root" show-ref --verify --quiet "refs/heads/$branch"; then
    git -C "$root" worktree add -q "$wt" "$branch" || die "could not create worktree"
  else
    git -C "$root" worktree add -q -b "$branch" "$wt" HEAD || die "could not create worktree"
  fi
fi
repo_git="$(git -C "$root" rev-parse --path-format=absolute --git-common-dir)" || die "could not identify project repository"
worktree_git="$(git -C "$wt" rev-parse --path-format=absolute --git-common-dir)" || die "invalid worktree: $wt"
if [ "$repo_git" != "$worktree_git" ] || [ "$(git -C "$wt" rev-parse --show-toplevel)" != "$wt" ] ||
   [ "$(git -C "$wt" symbolic-ref --quiet HEAD)" != "refs/heads/$branch" ]; then
  die "unexpected repository or branch at $wt"
fi
status="$(git -C "$wt" status --porcelain --untracked-files=all)" || die "could not inspect worktree: $wt"
[ -z "$status" ] || die "worktree contains changes: $wt (inspect or save the partial work before retrying)"
[ -n "$(git -C "$root" status --porcelain --untracked-files=no)" ] && \
  echo "NOTE: you have uncommitted changes; Codex's worktree starts from HEAD without them." >&2
model="$(cfg codex_model)"; t="$(cfg codex_timeout 2400)"
rm -f "$pending_receipt" || die "could not clear the previous partial receipt"
args=(exec --cd "$wt" --sandbox workspace-write --skip-git-repo-check --output-last-message "$pending_receipt")
[ -n "$model" ] && args+=(-m "$model")
echo "Codex working in $wt on branch $branch (timeout ${t}s)..."
start=$(date +%s)
run_with_timeout "$t" codex "${args[@]}" "$(cat "$ticket")" </dev/null >"$log" 2>&1; rc=$?
echo "Codex exit code: $rc after $(( $(date +%s) - start ))s"
if [ "$rc" -ne 0 ]; then
  echo "Dispatch failed. Worktree: $wt. Log: $log." >&2
  exit "$rc"
fi
[ -s "$pending_receipt" ] || die "Codex did not write a receipt. Worktree: $wt. Log: $log."
[ "$(git -C "$wt" symbolic-ref --quiet HEAD)" = "refs/heads/$branch" ] || die "Codex changed branches in $wt"
git -C "$wt" add -A || die "could not stage changes in $wt"
if git -C "$wt" diff --cached --quiet; then
  echo "Codex produced no file changes."
else
  [ "$?" -eq 1 ] || die "could not inspect staged changes in $wt"
  git -C "$wt" commit -q -m "codex: $slug" -m "Generated by Codex CLI from $(basename "$ticket")" || die "could not commit changes in $wt"
fi
git -C "$root" diff --stat "HEAD...$branch" >"$taskdir/05-codex-diffstat.txt" || die "could not record the worktree diff"
mv "$pending_receipt" "$receipt" || die "could not finalize the receipt"
echo "Receipt:  $receipt"; echo "Log:      $log"; echo "Branch:   $branch  (review with: git diff HEAD...$branch)"
echo "--- diff stat ---"; cat "$taskdir/05-codex-diffstat.txt"
